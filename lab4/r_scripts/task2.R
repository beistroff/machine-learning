cat("\014")

k_values <- c(10, 15, 20, 25, 30)

for (k in k_values) {
  # Генеруємо нормально розподілені випадкові величини з математичним сподіванням k і стандартним відхиленням sqrt(k)
  normal_sample <- rnorm(200, mean = k, sd = sqrt(k))
  
  # Генеруємо випадкові величини, що мають розподіл хі-квадрат з k ступенями вільності
  chisq_sample <- rchisq(200, df = k)
  
  # Використовуємо тест Колмогорова-Смірнова для перевірки гіпотези про однаковість розподілів
  ks_result <- ks.test(normal_sample, chisq_sample)
  
  cat("k =", k, "\n")
  cat("p-value тесту Колмогорова-Смірнова:", ks_result$p.value, "\n")
  cat("Статистика W:", ks_result$statistic, "\n")
  
  if(ks_result$p.value > 0.05){
    cat("Приймається гіпотеза про однаковість розподілів для k =", k, "\n")
  } else {
    cat("Відхиляємо гіпотезу про однаковість розподілів для k =", k, "\n\n")
  }
}